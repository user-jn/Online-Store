import java.util.Locale;

public class Product {
     // product attributes
     private String sku;
     private String name;
     private double price;
     private String department;

     // constructor
    public Product(String sku, String name, double price, String department) {

        this.sku = sku;
        this.name = name;
        this.price = price;
        this.department = department;
    }


}
